__mtrap:
    # Swap sp and mscratch to get kernel stack
    csrrw sp, mscratch, sp

    # Decrement stack pointer to make space for all registers (31 * 8 = 248 bytes)
    addi sp, sp, -248

    # Save all registers x1-x31 (we can include x0 for simplicity)
    sd x0, 0(sp)
    sd x1, 8(sp)
    sd x2, 16(sp)
    sd x3, 24(sp)
    sd x4, 32(sp)
    sd x5, 40(sp)
    sd x6, 48(sp)
    sd x7, 56(sp)
    sd x8, 64(sp)
    sd x9, 72(sp)
    sd x10, 80(sp)
    sd x11, 88(sp)
    sd x12, 96(sp)
    sd x13, 104(sp)
    sd x14, 112(sp)
    sd x15, 120(sp)
    sd x16, 128(sp)
    sd x17, 136(sp)
    sd x18, 144(sp)
    sd x19, 152(sp)
    sd x20, 160(sp)
    sd x21, 168(sp)
    sd x22, 176(sp)
    sd x23, 184(sp)
    sd x24, 192(sp)
    sd x25, 200(sp)
    sd x26, 208(sp)
    sd x27, 216(sp)
    sd x28, 224(sp)
    sd x29, 232(sp)
    sd x30, 240(sp)
    sd x31, 248(sp)

    # Get mcause and check if it's a misaligned load (cause 4)
    csrr t0, mcause
    li t1, 4
    bne t0, t1, not_misaligned_load

    # It's a misaligned load, get the instruction at mepc
    csrr t0, mepc
    lw t1, 0(t0)

    # Extract the destination register (rd) from instruction
    # rd is bits 7-11 of instruction
    li t2, 0xF80    # Mask for rd (bits 7-11)
    and t3, t1, t2  # Extract rd bits
    srli t3, t3, 7  # Shift right to get register number

    # Get the misaligned address from mtval
    csrr t0, mtval

    # Load 4 bytes individually and combine them
    lb t4, 0(t0)    # First byte
    lb t5, 1(t0)    # Second byte
    slli t5, t5, 8
    or t4, t4, t5
    lb t5, 2(t0)    # Third byte
    slli t5, t5, 16
    or t4, t4, t5
    lb t5, 3(t0)    # Fourth byte
    slli t5, t5, 24
    or t4, t4, t5

    # Store result in the saved register location
    slli t3, t3, 3  # Multiply register number by 8 for offset
    add t3, sp, t3  # Add to stack pointer
    sd t4, 0(t3)    # Store result in saved register location

    # Increment mepc to next instruction
    csrr t0, mepc
    addi t0, t0, 4
    csrw mepc, t0

    # Restore all registers
    ld x0, 0(sp)
    ld x1, 8(sp)
    ld x2, 16(sp)
    ld x3, 24(sp)
    ld x4, 32(sp)
    ld x5, 40(sp)
    ld x6, 48(sp)
    ld x7, 56(sp)
    ld x8, 64(sp)
    ld x9, 72(sp)
    ld x10, 80(sp)
    ld x11, 88(sp)
    ld x12, 96(sp)
    ld x13, 104(sp)
    ld x14, 112(sp)
    ld x15, 120(sp)
    ld x16, 128(sp)
    ld x17, 136(sp)
    ld x18, 144(sp)
    ld x19, 152(sp)
    ld x20, 160(sp)
    ld x21, 168(sp)
    ld x22, 176(sp)
    ld x23, 184(sp)
    ld x24, 192(sp)
    ld x25, 200(sp)
    ld x26, 208(sp)
    ld x27, 216(sp)
    ld x28, 224(sp)
    ld x29, 232(sp)
    ld x30, 240(sp)
    ld x31, 248(sp)

    # Restore stack pointer and swap back mscratch
    addi sp, sp, 248
    csrrw sp, mscratch, sp

    # Return from trap
    mret

not_misaligned_load:
    # Restore stack pointer and swap back mscratch before jumping to terminate
    addi sp, sp, 248
    csrrw sp, mscratch, sp
    j terminate





# This code is taken from the default VRV system code. It prints out
# a message indicating the cause of an unhandled exception. We are
# keeping this in this form to make it easier for you to debug.

# It is allowed to trash registers (unlike the normal trap handler)
# because it never returns
terminate:
    csrr    t0, mcause                                                        # Get mcause CSR
    li      t1, 0x80000000
    and     t1, t0, t1                                                        # mcause & 0x80000000
    beqz    t1, ____not_interrupt                                             # mcause has bit 31 set for an interrupt

# 2a. Interrupt
    la      a0, __m_int                                                       # Interrupt header message
    xor     t0, t0, t1                                                        # Isolate interrupt code
    la      t1, __ivec                                                        # Interrupt vector
    j       ____print_trap_message

# 2b. Exception
____not_interrupt:
    la      a0, __m_exc                                                       # Exception header message
    la      t1, __evec                                                        # Isolate exception code

# 3. Print header message
____print_trap_message:
    li      a7, PRINT_STR
    ecall

# 4. Print vector entry for this exception/interrupt
    slli    a0, t0, 2                                                         # mcause * 4
    add     a0, t1, a0                                                        # Index in vector
    lw      a0, (a0)                                                          # Entry from vector
    ecall

# 5. Print mcause
    la      a0, __m_mcause
    ecall
    csrr    a0, mcause
    li      a7, PRINT_HEX
    ecall

# 6. Print mepc
    la      a0, __m_mepc
    li      a7, PRINT_STR
    ecall
    csrr    a0, mepc
    li      a7, PRINT_HEX
    ecall

# 7. Print mtval
    la      a0, __m_mtval
    li      a7, PRINT_STR
    ecall
    csrr    a0, mtval
    li      a7, PRINT_HEX
    ecall
    li      a0, NEWLN_CHR
    li      a7, PRINT_CHR
    ecall

# Exit with code -1
    li      a0, -1
    li      a7, EXIT
    ecall



## User boot code
    .text
__user_bootstrap:
# exit(main())
    jal     main
    li      a7, EXIT
    ecall

# Useful utility function
kprintstr:
    li      a7, PRINT_STR
    ecall
    ret

